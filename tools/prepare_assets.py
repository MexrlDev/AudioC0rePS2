#!/usr/bin/env python3
"""Convert any logo image (png/jpg/jpeg/webp/bmp/gif) -> source/logo_data.c
   Produces a raw BGRA 500x500 pixel buffer as a C array."""
import sys
from PIL import Image

W = H = 500

def main():
    if len(sys.argv) != 3:
        print("usage: prepare_assets.py <logo image> <logo_data.c>")
        sys.exit(1)

    src = sys.argv[1]
    dst = sys.argv[2]

    try:
        img = Image.open(src)
    except Exception as e:
        print("ERROR: cannot open image '%s': %s" % (src, e))
        sys.exit(1)

    # Force to RGBA, resize to exactly W x H using high quality filter
    img = img.convert("RGBA")
    if img.size != (W, H):
        print("Resizing %dx%d -> %dx%d" % (img.size[0], img.size[1], W, H))
        img = img.resize((W, H), Image.LANCZOS)

    r, g, b, a = img.split()
    bgra = Image.merge("RGBA", (b, g, r, a))
    data = bgra.tobytes()
    assert len(data) == W * H * 4, len(data)

    with open(dst, "w") as f:
        f.write("/* Auto-generated by tools/prepare_assets.py — do not edit */\n")
        f.write('#include "app.h"\n\n')
        f.write("const int logo_width  = %d;\n" % W)
        f.write("const int logo_height = %d;\n\n" % H)
        f.write("const u32 logo_data[%d] = {\n" % (W * H))
        row = []
        for i in range(0, len(data), 4):
            px = data[i] | (data[i+1] << 8) | (data[i+2] << 16) | (data[i+3] << 24)
            row.append("0x%08X" % px)
            if len(row) == 8:
                f.write("    " + ",".join(row) + ",\n")
                row = []
        if row:
            f.write("    " + ",".join(row) + ",\n")
        f.write("};\n")

    print("Wrote %s: %d pixels (%d bytes source)" % (dst, W * H, len(data)))

if __name__ == "__main__":
    main()
